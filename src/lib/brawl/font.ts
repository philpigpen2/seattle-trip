const cache = new Map<string, string[]>();

function rows(ch: string): string[] {
  const key = ch.toUpperCase();
  let r = cache.get(key);
  if (!r) {
    r = (G[key] ?? G["?"]).split(".");
    cache.set(key, r);
  }
  return r;
}

export function textWidth(text: string, scale = 1, tracking = 1): number {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

export type TextOpts = {
  scale?: number;
  tracking?: number;
  shadow?: string;
  align?: "left" | "center" | "right";
};

/** Draws pixel text with its top-left at (x, y) unless `align` says otherwise. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  opts: TextOpts = {},
): void {
  const scale = opts.scale ?? 1;
  const tracking = opts.tracking ?? 1;
  const w = textWidth(text, scale, tracking);
  let px = x;
  if (opts.align === "center") px = Math.round(x - w / 2);
  else if (opts.align === "right") px = Math.round(x - w);

  const step = (GLYPH_W + tracking) * scale;

  for (const pass of opts.shadow ? [1, 0] : [0]) {
    ctx.fillStyle = pass === 1 ? opts.shadow! : color;
    const ox = pass === 1 ? scale : 0;
    const oy = pass === 1 ? scale : 0;
    for (let i = 0; i < text.length; i++) {
      const r = rows(text[i]);
      const gx = px + i * step + ox;
      for (let ry = 0; ry < GLYPH_H; ry++) {
        const row = r[ry];
        for (let rx = 0; rx < GLYPH_W; rx++) {
          if (row[rx] === "1") {
            ctx.fillRect(gx + rx * scale, y + ry * scale + oy, scale, scale);
          }
        }
      }
    }
  }
}
